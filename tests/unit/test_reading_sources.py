"""Reading evidence is selected as exact original windows before semantic review."""

import json

import pytest

from paper_review.application.full_analysis import source_spans
from paper_review.application.reading_sources import WINDOW_LIMIT, reading_source_windows
from paper_review.domain.models import PaperSection
from paper_review.domain.section_titles import is_bibliography_heading
from paper_review.domain.understanding import ReasoningFlow, validate_evidence
from paper_review.llm.gateway import bind_source_evidence, prepare_source_request, request_schema


def source(sid, text, start=0, **changes):
    return {
        "span_id": sid, "paper_id": "p", "revision": "v1", "section_id": "s",
        "section": "3 Method", "page": "1", "start_offset": str(start),
        "end_offset": str(start + len(text)), "text": text, **changes,
    }


def test_window_selection_covers_a_sentence_cut_across_old_chunks():
    statement = "The preferences are assumed to be generated by some latent reward model."
    text = "Earlier context. " * 23 + statement + " We cannot access that model."
    original = [source(str(i), text[i:i+400], i) for i in range(0, len(text), 400)]
    assert not any(statement in s["text"] for s in original)
    windows = reading_source_windows(original)
    assert len(windows) == 1 and statement in windows[0]["text"]
    assert json.loads(windows[0]["source_span_ids"]) == [s["span_id"] for s in original]
    _, context, aliases = prepare_source_request(
        request_schema(ReasoningFlow, bind_evidence=True), tuple(windows)
    )
    selected = bind_source_evidence(
        {"evidence": [{"span_id": context[0]["span_id"]}]},
        {key: value[1] for key, value in aliases.items()},
        original_ids={key: value[0] for key, value in aliases.items()},
    )
    from paper_review.domain.understanding import Evidence

    evidence = [Evidence.model_validate(e) for e in selected["evidence"]]
    validate_evidence(evidence, {s["span_id"]: s for s in windows})
    assert len(evidence) == 1 and evidence[0].quote == text


@pytest.mark.parametrize("barrier", ["gap", "revision", "section", "ambiguous"])
def test_windows_never_join_missing_or_ambiguous_source_text(barrier):
    a = source("a", "First part")
    b = source("b", " and its continuation.", len(a["text"]))
    original = [a, b]
    if barrier == "gap":
        b.update(start_offset="11", end_offset=str(11 + len(b["text"])))
    elif barrier == "revision":
        b["revision"] = "v2"
    elif barrier == "section":
        b["section_id"] = "other"
    else:
        original.insert(1, {**a, "span_id": "duplicate"})
    result = reading_source_windows(original)
    assert len(result) == len(original)
    assert all(len(json.loads(s["source_span_ids"])) == 1 for s in result)


def test_sentence_windows_keep_offsets_and_unknown_cross_page_provenance():
    text = "A sentence with its condition and conclusion. " * 70
    section = PaperSection(
        id="s", paper_id="p", revision_id="v1", section_index=0, title="Results",
        text=text, page_start=1, page_end=2,
        span_info={"source_spans": [
            {"start_offset": 0, "end_offset": 1500, "page": 1},
            {"start_offset": 1500, "end_offset": len(text), "page": 2},
        ]},
    )
    result = reading_source_windows(source_spans([section]))
    assert "".join(s["text"] for s in result) == text
    assert all(len(s["text"]) <= WINDOW_LIMIT for s in result)
    assert any(s["page"] == "unknown" for s in result)
    for span in result:
        assert text[int(span["start_offset"]):int(span["end_offset"])] == span["text"]
    assert all(s["end_boundary"] == "sentence_boundary" for s in result[:-1])


def test_length_limited_source_stays_explicitly_truncated_and_small_sources_keep_ids():
    long = source("long", "x" * (WINDOW_LIMIT + 10))
    a, b = reading_source_windows([long])
    assert a["end_boundary"] == b["start_boundary"] == "length_limit"
    assert a["text"] + b["text"] == long["text"]
    small = source("small", "A complete sentence.")
    assert reading_source_windows([small])[0]["span_id"] == "small"


@pytest.mark.parametrize("title", ["References", "8 References", "Bibliography", "A References"])
def test_bibliography_headings_are_recognized(title):
    assert is_bibliography_heading(title)


@pytest.mark.parametrize("title", [
    "4 Direct Preference Optimization",
    "6.2 Can DPO scale to real preference datasets?",
    "Reference model construction",
])
def test_preference_methods_and_results_are_never_discarded_as_bibliography(title):
    assert not is_bibliography_heading(title)
    section = PaperSection(
        id="s", paper_id="p", revision_id="v1", section_index=0, title=title,
        text="The summarization experiment reports its result.", page_start=1, page_end=1,
    )
    assert source_spans([section])[0]["text"] == section.text
